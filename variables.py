# This program demonstrates basic variables/data types.

# Declaring each variable with name and appropriate data type
name = "Kyle Clifton"       # String
age = 39                    # Integer
height = 1.85               # Float
liking_python = True        # Boolean

# Printing each variable
print("Name:", name)                        # Should output Name: Kyle Clifton
print("Age:", age)                          # Should output Age: 39
print("Height:", height, "m")               # Should output Height: 1.85 m
print("Liking Python?:", liking_python)     # Should output Liking Python?: True
